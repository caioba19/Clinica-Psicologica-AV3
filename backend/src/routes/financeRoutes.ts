import { Router } from 'express';
import { authenticateToken, requireRole } from '../middlewares/authMiddleware';
import { FinanceController } from '../controllers/financeController';
import { FinanceRepository } from '../repositories/FinanceRepository';
const routes = Router();
const controller = new FinanceController(new FinanceRepository());
routes.get('/finance', authenticateToken, requireRole(['administrador', 'psicologo']), controller.list);
routes.post('/finance', authenticateToken, requireRole(['administrador', 'psicologo']), controller.create);
routes.delete('/finance/:id', authenticateToken, requireRole(['administrador', 'psicologo']), controller.delete);
export { routes as financeRoutes };
